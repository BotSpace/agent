"""Prometheus counters for LLM token accounting.

We separate **input tokens by category** so dashboards can answer
"where does the spend go?" — system prompt, tool schemas, user
messages, tool results, plus the cache_read / cache_write split that
OpenRouter reports in `usage.prompt_tokens_details`.

The per-category split (system / tool_schema / user / tool_result) is
counted **locally** at request-build time using a cheap chars/4
heuristic — OpenRouter does not break input down by section. The
cache_read / cache_write / uncached split comes from the provider's
usage object verbatim.

Labels deliberately small (model, provider) to keep cardinality bounded.
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING

from prometheus_client import Counter, Histogram

if TYPE_CHECKING:
    from ..llm.base import GenerateOptions, Message


LLM_INPUT_TOKENS = Counter(
    "agent_llm_input_tokens_total",
    "Input tokens sent to LLM, broken down by category.",
    labelnames=("provider", "model", "category"),
)
# category ∈ {system, tool_schema, user, tool_result, cache_read,
#             cache_write, uncached, prompt_total}
#   system/tool_schema/user/tool_result — locally estimated (chars/4)
#   cache_read/cache_write/uncached/prompt_total — from provider usage
# Both groups should sum to ~prompt_total; if not, treat the local
# estimate as approximate.

LLM_OUTPUT_TOKENS = Counter(
    "agent_llm_output_tokens_total",
    "Output (completion) tokens generated by LLM.",
    labelnames=("provider", "model"),
)

LLM_REQUESTS = Counter(
    "agent_llm_requests_total",
    "LLM chat-completions requests.",
    labelnames=("provider", "model", "outcome"),  # outcome: success|error
)

LLM_REQUEST_DURATION = Histogram(
    "agent_llm_request_duration_seconds",
    "LLM request wall-clock duration.",
    labelnames=("provider", "model"),
    buckets=(0.1, 0.25, 0.5, 1.0, 2.0, 5.0, 10.0, 20.0, 60.0, 120.0),
)

# ── run-level metrics ───────────────────────────────────────────────────────
# "AI'dan foydalanish" ni vaqt bo'yicha ko'rsatadi: rate(agent_runs_total)
# qaysi soatlarda ko'p ishlatilishini beradi.
AGENT_RUNS = Counter(
    "agent_runs_total",
    "Agent run'lari yakunlangani bo'yicha.",
    labelnames=("outcome",),  # outcome: completed | failed
)

AGENT_RUN_DURATION = Histogram(
    "agent_run_duration_seconds",
    "Bitta agent run'ining to'liq davomiyligi (wall-clock).",
    buckets=(0.5, 1.0, 2.5, 5.0, 10.0, 20.0, 30.0, 60.0, 120.0, 300.0, 600.0),
)


def local_token_breakdown(
    messages: list[Message],
    options: GenerateOptions,
) -> dict[str, int]:
    """Estimate input tokens by category for Prometheus.

    Uses a chars/4 heuristic so we don't pull tiktoken in just for
    observability. The split is approximate but still useful to see
    relative shares (system vs user vs tool_result).

    Shared by all LLM providers (openai, bedrock, anthropic).
    """
    from ..llm.base import ToolResultPart

    system_chars = 0
    user_chars = 0
    tool_result_chars = 0
    for m in messages:
        if m.role == "system":
            system_chars += len(m.text)
        elif m.role == "user":
            user_chars += len(m.text)
        elif m.role == "tool":
            for p in m.content:
                if isinstance(p, ToolResultPart):
                    tool_result_chars += len(p.content)
    tool_schema_chars = 0
    for t in options.tools or []:
        tool_schema_chars += len(t.name) + len(t.description or "")
        tool_schema_chars += len(json.dumps(t.input_schema))
    return {
        "system": (system_chars + 3) // 4,
        "tool_schema": (tool_schema_chars + 3) // 4,
        "user": (user_chars + 3) // 4,
        "tool_result": (tool_result_chars + 3) // 4,
    }


def record_llm_usage(
    *,
    provider: str,
    model: str,
    usage: dict | None,
    local_breakdown: dict[str, int] | None = None,
) -> None:
    """Increment input/output counters from an LLM response's usage payload.

    Supports three usage dict shapes:

    OpenAI / OpenRouter flavor:
        {
          "prompt_tokens": int,
          "completion_tokens": int,
          "prompt_tokens_details": {
              "cached_tokens": int,         # cache READ
              "cache_write_tokens": int,    # cache WRITE (optional)
          }
        }

    Bedrock Converse flavor:
        {
          "inputTokens": int,
          "outputTokens": int,
          "cacheReadInputTokens": int,      # optional, cache READ
          "cacheWriteInputTokens": int,     # optional, cache WRITE
        }

    Anthropic SDK flavor:
        {
          "input_tokens": int,
          "output_tokens": int,
          "cache_read_input_tokens": int,   # optional, cache READ
          "cache_creation_input_tokens": int, # optional, cache WRITE
        }

    Missing cache fields default to 0 — tolerant of cache-less models.

    local_breakdown (optional): {"system": int, "tool_schema": int,
        "user": int, "tool_result": int} — locally-estimated category
        totals for this request, recorded alongside the provider counts.
    """
    if not usage:
        return

    # Normalize to a common shape regardless of provider flavor.
    # OpenAI/OpenRouter: prompt_tokens / completion_tokens
    # Bedrock: inputTokens / outputTokens
    # Anthropic SDK: input_tokens / output_tokens
    prompt_total = int(
        usage.get("prompt_tokens")
        or usage.get("inputTokens")
        or usage.get("input_tokens")
        or 0
    )
    completion = int(
        usage.get("completion_tokens")
        or usage.get("outputTokens")
        or usage.get("output_tokens")
        or 0
    )

    # Cache READ tokens
    details = usage.get("prompt_tokens_details") or {}
    cached_read = int(
        details.get("cached_tokens")
        or usage.get("cacheReadInputTokens")
        or usage.get("cache_read_input_tokens")
        or 0
    )

    # Cache WRITE tokens
    cache_write = int(
        details.get("cache_write_tokens")
        or usage.get("cacheWriteInputTokens")
        or usage.get("cache_creation_input_tokens")
        or 0
    )

    uncached = max(0, prompt_total - cached_read - cache_write)

    LLM_INPUT_TOKENS.labels(provider, model, "prompt_total").inc(prompt_total)
    LLM_INPUT_TOKENS.labels(provider, model, "cache_read").inc(cached_read)
    LLM_INPUT_TOKENS.labels(provider, model, "cache_write").inc(cache_write)
    LLM_INPUT_TOKENS.labels(provider, model, "uncached").inc(uncached)
    LLM_OUTPUT_TOKENS.labels(provider, model).inc(completion)

    if local_breakdown:
        for cat in ("system", "tool_schema", "user", "tool_result"):
            v = int(local_breakdown.get(cat) or 0)
            if v:
                LLM_INPUT_TOKENS.labels(provider, model, cat).inc(v)
