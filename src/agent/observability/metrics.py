"""Prometheus counters for LLM token accounting.

We separate **input tokens by category** so dashboards can answer
"where does the spend go?" — system prompt, tool schemas, user
messages, tool results, plus the cache_read / cache_write split that
OpenRouter reports in `usage.prompt_tokens_details`.

The per-category split (system / tool_schema / user / tool_result) is
counted **locally** at request-build time using a cheap chars/4
heuristic — OpenRouter does not break input down by section. The
cache_read / cache_write / uncached split comes from the provider's
usage object verbatim.

Labels deliberately small (model, provider) to keep cardinality bounded.
"""

from __future__ import annotations

from prometheus_client import Counter, Histogram


LLM_INPUT_TOKENS = Counter(
    "agent_llm_input_tokens_total",
    "Input tokens sent to LLM, broken down by category.",
    labelnames=("provider", "model", "category"),
)
# category ∈ {system, tool_schema, user, tool_result, cache_read,
#             cache_write, uncached, prompt_total}
#   system/tool_schema/user/tool_result — locally estimated (chars/4)
#   cache_read/cache_write/uncached/prompt_total — from provider usage
# Both groups should sum to ~prompt_total; if not, treat the local
# estimate as approximate.

LLM_OUTPUT_TOKENS = Counter(
    "agent_llm_output_tokens_total",
    "Output (completion) tokens generated by LLM.",
    labelnames=("provider", "model"),
)

LLM_REQUESTS = Counter(
    "agent_llm_requests_total",
    "LLM chat-completions requests.",
    labelnames=("provider", "model", "outcome"),  # outcome: success|error
)

LLM_REQUEST_DURATION = Histogram(
    "agent_llm_request_duration_seconds",
    "LLM request wall-clock duration.",
    labelnames=("provider", "model"),
    buckets=(0.1, 0.25, 0.5, 1.0, 2.0, 5.0, 10.0, 20.0, 60.0, 120.0),
)


def _estimate_tokens(text: str) -> int:
    """Cheap chars-per-token estimate. Not exact, but fine for a
    relative breakdown (system vs user vs tool_result). Replace with
    tiktoken if accuracy matters."""
    return max(0, (len(text) + 3) // 4)


def record_llm_usage(
    *,
    provider: str,
    model: str,
    usage: dict | None,
    local_breakdown: dict[str, int] | None = None,
) -> None:
    """Increment input/output counters from an LLM response's usage payload.

    usage shape (OpenRouter-normalized OpenAI flavor):
        {
          "prompt_tokens": int,
          "completion_tokens": int,
          "prompt_tokens_details": {
              "cached_tokens": int,         # cache READ
              "cache_write_tokens": int,    # cache WRITE (optional)
          }
        }

    local_breakdown (optional): {"system": int, "tool_schema": int,
        "user": int, "tool_result": int} — locally-estimated category
        totals for this request, recorded alongside the provider counts.
    """
    if not usage:
        return
    prompt_total = int(usage.get("prompt_tokens") or 0)
    completion = int(usage.get("completion_tokens") or 0)
    details = usage.get("prompt_tokens_details") or {}
    cached_read = int(details.get("cached_tokens") or 0)
    cache_write = int(details.get("cache_write_tokens") or 0)
    uncached = max(0, prompt_total - cached_read - cache_write)

    LLM_INPUT_TOKENS.labels(provider, model, "prompt_total").inc(prompt_total)
    LLM_INPUT_TOKENS.labels(provider, model, "cache_read").inc(cached_read)
    LLM_INPUT_TOKENS.labels(provider, model, "cache_write").inc(cache_write)
    LLM_INPUT_TOKENS.labels(provider, model, "uncached").inc(uncached)
    LLM_OUTPUT_TOKENS.labels(provider, model).inc(completion)

    if local_breakdown:
        for cat in ("system", "tool_schema", "user", "tool_result"):
            v = int(local_breakdown.get(cat) or 0)
            if v:
                LLM_INPUT_TOKENS.labels(provider, model, cat).inc(v)
